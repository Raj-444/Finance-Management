<?php
declare(strict_types=1);

/**
 * cPanel Release Packager
 * Generates a clean, production-ready ZIP archive for direct upload to cPanel.
 */

if (php_sapi_name() !== 'cli') {
    die("CLI only.\n");
}

$rootDir = dirname(__DIR__);
$distDir = $rootDir . '/dist';
if (!is_dir($distDir)) {
    mkdir($distDir, 0755, true);
}

$zipPath = $distDir . '/personal_finance_manager_cpanel.zip';
@unlink($zipPath);

if (!class_exists(\ZipArchive::class)) {
    die("Error: PHP ZipArchive extension is required to generate release package.\n");
}

$zip = new \ZipArchive();
if ($zip->open($zipPath, \ZipArchive::CREATE | \ZipArchive::OVERWRITE) !== true) {
    die("Error: Could not create ZIP file at {$zipPath}\n");
}

echo "==> Packaging Personal Finance Manager for cPanel release...\n";

// Blacklist patterns to exclude from production package
$excludePatterns = [
    '/\.git/',
    '/\.github/',
    '/tests/',
    '/dist/',
    '/\.idea/',
    '/\.vscode/',
    '/storage\/database\.sqlite/',
    '/storage\/test_.*\.sqlite/',
    '/storage\/installed\.lock/',
    '/storage\/cron\.lock/',
    '/storage\/sessions\/sess_/',
    '/storage\/logs\/.*\.log/',
    '/config\/config\.php/', // Will be generated by web installer
];

$filesAdded = 0;

$addFolder = function (string $folder, string $zipPrefix) use (&$addFolder, $zip, $excludePatterns, &$filesAdded, $rootDir) {
    $dir = new \RecursiveDirectoryIterator($folder, \RecursiveDirectoryIterator::SKIP_DOTS);
    $iterator = new \RecursiveIteratorIterator($dir, \RecursiveIteratorIterator::SELF_FIRST);

    foreach ($iterator as $item) {
        $fullPath = $item->getPathname();
        $relativePath = substr($fullPath, strlen($rootDir) + 1);
        $relativePathNormalized = str_replace('\\', '/', $relativePath);

        // Check exclusions
        $skip = false;
        foreach ($excludePatterns as $pattern) {
            if (preg_match($pattern, $relativePathNormalized)) {
                $skip = true;
                break;
            }
        }

        if ($skip) {
            continue;
        }

        $localName = $zipPrefix . '/' . substr($fullPath, strlen($folder) + 1);
        $localName = str_replace('\\', '/', $localName);

        if ($item->isDir()) {
            $zip->addEmptyDir($localName);
        } elseif ($item->isFile()) {
            $zip->addFile($fullPath, $localName);
            $filesAdded++;
        }
    }
};

// 1. Add finance_app directory
echo "==> Adding finance_app/ ...\n";
$addFolder($rootDir . '/finance_app', 'finance_app');

// Ensure empty storage directories exist in package
$zip->addEmptyDir('finance_app/storage/logs');
$zip->addEmptyDir('finance_app/storage/sessions');
$zip->addEmptyDir('finance_app/storage/cache');
$zip->addEmptyDir('finance_app/storage/backups');
$zip->addEmptyDir('finance_app/storage/tmp');

// 2. Add public_html directory
echo "==> Adding public_html/ ...\n";
$addFolder($rootDir . '/public_html', 'public_html');

$zip->close();

$sizeMb = round(filesize($zipPath) / 1024 / 1024, 2);

echo "\n========================================================\n";
echo "Package successfully generated!\n";
echo "File:     {$zipPath}\n";
echo "Size:     {$sizeMb} MB ({$filesAdded} files)\n";
echo "========================================================\n\n";
echo "Deployment Instructions:\n";
echo "1. Upload 'personal_finance_manager_cpanel.zip' to your cPanel File Manager in /home/username/\n";
echo "2. Extract the archive. It will place:\n";
echo "   - 'finance_app/' in /home/username/finance_app (secure, above web root)\n";
echo "   - Contents of 'public_html/' in your domain's public_html/ folder\n";
echo "3. Open your browser to https://yourdomain.com/install\n";
echo "4. Follow the setup wizard and configure MySQL credentials.\n";
